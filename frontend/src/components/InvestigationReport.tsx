import ServiceMap from './ServiceMap'
import type {
  HypothesisStatus,
  InvestigationResult,
  RecommendedAction,
} from '../api/types'
import RemediationPanel from './RemediationPanel'
import SeenBefore from './SeenBefore'

const HYPOTHESIS_CLASS: Record<HypothesisStatus, string> = {
  SUPPORTED: 'hyp-supported',
  PLAUSIBLE: 'hyp-plausible',
  REJECTED: 'hyp-rejected',
}

// A stable empty list, so the approval panel is not reset by every re-render.
const NO_ACTIONS: RecommendedAction[] = []

const ISO_LIKE = /^\d{4}-\d{2}-\d{2}T/

// Accepts "HH:MM:SS" (shown as is) and full ISO timestamps (shown in UTC).
function formatEventTime(raw: string) {
  if (!ISO_LIKE.test(raw)) return raw
  const ms = Date.parse(raw)
  if (Number.isNaN(ms)) return raw
  const text = new Intl.DateTimeFormat('en-GB', {
    day: '2-digit',
    month: 'short',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: false,
    timeZone: 'UTC',
  }).format(new Date(ms))
  return `${text} UTC`
}

function capitalize(value: string) {
  return value.charAt(0) + value.slice(1).toLowerCase()
}

type InvestigationReportProps = {
  result: InvestigationResult
  cachedAt?: string | null
}

function InvestigationReport({ result, cachedAt = null }: InvestigationReportProps) {
  const timeline = result.timeline ?? []
  const hypotheses = result.hypotheses_evaluated ?? []
  const evidence = result.evidence ?? []
  const actions = result.recommended_actions ?? NO_ACTIONS
  const confidence = Math.max(0, Math.min(100, result.confidence_pct ?? 0))
  const fromModel = result.source === 'llm'
  const memory = result as typeof result & {
    similar_past_incident?: unknown
    memory_source?: string
  }

  return (
    <div className="report">
      {cachedAt ? (
        <div className="notice notice-warn" role="status">
          <span className="badge source-fallback">Cached</span>
          <p>
            The backend could not be reached, so this is the last real answer saved on this
            computer ({new Date(cachedAt).toLocaleString()}). It is not a fresh investigation,
            and approving a fix needs the backend to be running.
          </p>
        </div>
      ) : null}

      <section className="panel" aria-labelledby="summary-heading">
        <h2 id="summary-heading">
          {result.incident_id} · <code>{result.service}</code>
        </h2>

        <div className={`notice ${fromModel ? 'notice-info' : 'notice-warn'}`}>
          <span className={`badge ${fromModel ? 'source-llm' : 'source-fallback'}`}>
            {fromModel ? `AI model · ${result.model ?? 'unknown model'}` : 'Fallback answer'}
          </span>
          {memory.memory_source ? (
            <span className="badge memory-badge" title="Where the past-incident match came from">
              Memory · {memory.memory_source}
            </span>
          ) : null}
          <p>
            {fromModel
              ? 'Generated by the AI model and checked by the backend before it reached this page.'
              : 'The AI model was not used for this answer. The backend returned a prepared fallback result (the model failed, or no API key is configured). Treat it as a recorded example, not a fresh investigation.'}
          </p>
        </div>

        <p className="kind-label">Inferred by the agent</p>
        <p className="root-cause">{result.root_cause}</p>

        <div className="confidence" aria-label={`Confidence ${confidence} percent`}>
          <div className="confidence-bar" aria-hidden="true">
            <span style={{ width: `${confidence}%` }} />
          </div>
          <strong>{confidence}%</strong>
          <span className="muted">{result.confidence} confidence</span>
        </div>
        <p className="caveat">
          Confidence is reported by the investigation agent. It is not statistically calibrated.
        </p>
      </section>
      <SeenBefore past={memory.similar_past_incident} />
      <ServiceMap result={result} />
      <div className="report-grid">
        <section className="panel" aria-labelledby="timeline-heading">
          <h2 id="timeline-heading">Timeline</h2>
          <p className="kind-label">Observed · events from the incident logs</p>
          {timeline.length === 0 ? (
            <p className="empty">No timeline events were returned.</p>
          ) : (
            <ol className="timeline-list">
              {timeline.map((event, index) => (
                <li key={`${event.timestamp}-${index}`}>
                  <span className="tl-time">{formatEventTime(event.timestamp)}</span>
                  <span className="tl-source">{event.source}</span>
                  <p>{event.message}</p>
                </li>
              ))}
            </ol>
          )}
        </section>

        <section className="panel" aria-labelledby="hypotheses-heading">
          <h2 id="hypotheses-heading">Competing hypotheses</h2>
          <p className="kind-label">Inferred · judged against the timeline</p>
          {hypotheses.length === 0 ? (
            <p className="empty">No hypotheses were returned.</p>
          ) : (
            <ul className="hyp-list">
              {hypotheses.map((hypothesis) => (
                <li key={hypothesis.id}>
                  <div className="hyp-head">
                    <span className="hyp-id">{hypothesis.id}</span>
                    <strong>{hypothesis.title}</strong>
                    <span className={`badge ${HYPOTHESIS_CLASS[hypothesis.status] ?? ''}`}>
                      {capitalize(hypothesis.status)}
                    </span>
                  </div>
                  <p>{hypothesis.reason}</p>
                </li>
              ))}
            </ul>
          )}
        </section>

        <section className="panel" aria-labelledby="evidence-heading">
          <h2 id="evidence-heading">Evidence cited</h2>
          <p className="kind-label">Written by the agent · not yet linked to log lines</p>
          {evidence.length === 0 ? (
            <p className="empty">The agent cited no evidence.</p>
          ) : (
            <ul className="plain-list">
              {evidence.map((item, index) => (
                <li key={index}>{item}</li>
              ))}
            </ul>
          )}
        </section>
      </div>

      <RemediationPanel incidentId={result.incident_id} actions={actions} />
    </div>
  )
}

export default InvestigationReport